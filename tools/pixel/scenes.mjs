/** 远景：一排低对比剪影 + 雾带，制造纵深。中央刻意压低，给玩法留干净区 */
function distantLayer(c, ramp, seed = 7) {
  let s = seed >>> 0;
  const rnd = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
  const horizon = BG_H * 0.72;
  for (let i = 0; i < 9; i++) {
    const x = 20 + i * 52 + rnd() * 16;
    const h = 18 + rnd() * 26;
    const w = 46 + rnd() * 30;
    // 中央 1/3 压矮，避免抢玩法区
    const k = Math.abs(x - BG_W / 2) < BG_W / 6 ? 0.45 : 1;
    for (let y = 0; y < h * k; y++) {
      const t = y / (h * k);
      const half = (w / 2) * (1 - t * 0.85);
      c.fillRect(x - half, horizon - y, Math.max(1, half * 2), 1, ramp[0]);
    }
  }
  // 雾带：把远景压进背景（规则 3 明暗分离）
  c.ditherFill(0, horizon - 20, BG_W, 20, [0, 0, 0, 0], ramp[0], (x, y) => 1 - y / 20);
}

/** 生成一张背景 */
export function makeBackground(id, ramp) {
  const c = new Canvas(BG_W, BG_H);
  sky(c, ramp);
  specks(c, ramp, id === 'zhutian' || id === 'settle' ? 220 : 90, id.length * 7 + 3);
  distantLayer(c, ramp, id.length * 13 + 5);
  ground(c, ramp);
  (LANDMARKS[id] ?? LANDMARKS.nest)(c, ramp);
  // 前景压暗条：把玩法区域从背景里「托」出来（规则 3 明暗分离）
  c.ditherFill(0, BG_H - 34, BG_W, 34, ramp[0], P.void[0], (x, y) => y / 34);
  return c;
}

