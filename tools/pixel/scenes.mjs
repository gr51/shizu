// ===== pixel/scenes.mjs · 背景 / 图标 / UI / 入口 =====
// 背景不用 ASCII（480×270 太大），改**程序化分层剪影**：
//   天空抖动渐变 → 远景地标剪影 → 中景 → 地面 → 前景装饰
// 每个位面一套**专属地标生成器**，形状语言按规则 5（几何/弧线/有机/动势/块面）。
// 构图守规则 8「负空间」：地标居中偏下、左右留空，中央给玩法留干净区域。

import { Canvas } from './canvas.mjs';
import { P, INK, rgb } from './palette.mjs';

/** 背景原生分辨率（×4 = 1920×1080） */
export const BG_W = 480;
export const BG_H = 270;

/** 天空：两段抖动渐变（上深下亮），像素风的标准做法 */
function sky(c, ramp) {
  c.ditherFill(0, 0, BG_W, BG_H, P.void[0], ramp[0], (x, y) => (y / BG_H) * 0.9);
  c.ditherFill(0, BG_H * 0.45, BG_W, BG_H * 0.55, ramp[0], ramp[1],
    (x, y) => y / (BG_H * 0.55));
}

/** 地面：水平线 + 下方实色 + 一排抖动过渡 */
function ground(c, ramp, horizon = BG_H * 0.72) {
  c.fillRect(0, horizon, BG_W, BG_H - horizon, ramp[0]);
  c.ditherFill(0, horizon - 6, BG_W, 12, ramp[1], ramp[0], (x, y) => y / 12);
  c.fillRect(0, horizon, BG_W, 1, ramp[2]);
}

/** 星点 / 尘埃（固定伪随机，保证可复现） */
function specks(c, ramp, n, seed = 1) {
  let s = seed >>> 0;
  const rnd = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
  for (let i = 0; i < n; i++) {
    const x = (rnd() * BG_W) | 0;
    const y = (rnd() * BG_H * 0.65) | 0;
    c.px(x, y, rnd() > 0.6 ? ramp[3] : ramp[2]);
  }
}

// ——— 各位面地标（形状语言按规则 5）———

/** 诡术：几何 · 直线 · 齿轮 */
function gear(c, cx, cy, r, col) {
  c.ellipse(cx, cy, r, r, col);
  c.ellipse(cx, cy, r * 0.45, r * 0.45, P.void[0]);
  for (let i = 0; i < 8; i++) {
    const a = (i / 8) * Math.PI * 2;
    c.fillRect(cx + Math.cos(a) * r - 3, cy + Math.sin(a) * r - 3, 7, 7, col);
  }
}

/** 仙途：弧线 · 塔 / 莲 */
function pagoda(c, cx, base, h, col) {
  for (let i = 0; i < 5; i++) {
    const w = 40 - i * 6;
    const y = base - (i + 1) * (h / 5);
    c.fillRect(cx - w / 2, y, w, h / 5 - 1, col);
    c.fillRect(cx - w / 2 - 4, y, w + 8, 2, col);
  }
}

/** 异变：有机 · 曲线 · 孢子囊 */
function pod(c, cx, base, h, col) {
  for (let y = 0; y < h; y++) {
    const t = y / h;
    const w = Math.sin(t * Math.PI) * 16 + 3;
    c.fillRect(cx - w, base - y, w * 2, 1, col);
  }
}

/** 武炼：动势 · 山峦（底宽顶尖 —— 早期版本插值方向反了，画成了倒三角） */
function peak(c, cx, base, h, w, col) {
  for (let y = 0; y < h; y++) {
    const t = y / h;                 // 0 = 山脚，1 = 山顶
    const half = (w / 2) * (1 - t);  // 越往上越窄
    c.fillRect(cx - half, base - y, Math.max(1, half * 2), 1, col);
  }
}

/** 钢铁：块面 · 直角 · 塔架 */
function rigTower(c, cx, base, h, col) {
  c.fillRect(cx - 8, base - h, 16, h, col);
  for (let i = 1; i < 5; i++) {
    const y = base - (h * i) / 5;
    c.fillRect(cx - 18, y, 36, 3, col);
  }
}

