/** 是否被永久封印 */
export function 是否封印(存档, 路线) {
  return 存档.player.封印路线.includes(路线);
}

/** 路线是否已激活（解锁 ≥1 段） */
export function 已激活(存档, 路线) {
  return (存档.player.基因锁[路线] || 0) > 0;
}

/** 已激活路线列表 */
export function 已激活路线(存档) {
  return 路线列表.filter((r) => 已激活(存档, r));
}
