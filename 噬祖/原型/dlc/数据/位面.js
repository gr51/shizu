export function 查找位面(名) {
  return 位面表.find((p) => p.名 === 名);
}

/**
 * 位面随机权重：
 * - 已激活路线位面 ×2 / 未激活 ×1 / 互斥 ×0 / 诸天之心 ×1
 * - 首次副本固定机关城（教学）
 */
export function 位面权重(存档, 位面) {
  if (位面.名 === '机关城' && 存档.player.总次数 === 0) return 999; // 首局固定教学
  if (位面.名 === '诸天之心') return 1;
  if (!位面.路线) return 1; // 奇巧迷宫（奇技/魔法双基因）
  if (存档.player.封印路线.includes(位面.路线)) return 0;  // 互斥封印
  return 已激活(存档, 位面.路线) ? 2 : 1;
}

/** 副本蓝图：seed 驱动生成 5 阶段 */
export function 生成蓝图(存档, 位面, rng) {
  const D = 副本难度(存档);
  const 阶段系数 = [0.9, 1.0, 1.15, 1.3];
  const stages = [];
  for (let s = 1; s <= 5; s++) {
    const 系数 = s === 5 ? 1.1 + rng() * 0.05 : 阶段系数[s - 1];
    stages.push({
      阶段: s,
      波次: s === 5 ? 1 : 位面.波次[s - 1],
      系数,
      D,
      精英: (s === 3 || s === 4) ? { 名: `${位面.主题}·精英`, HP: 位面.精HP * D * 系数, 攻: 位面.精攻 * D * 系数 } : null,
    });
  }
  return { 位面, 难度值: D, 阶段: stages };
}
